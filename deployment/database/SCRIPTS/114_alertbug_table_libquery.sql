-- ALERTBUG — patch / bug-fix history per alert (ALERTS.ALTID)
--
-- Deploy on ICR app DB after 101_alerts_altspec.sql.
-- Re-runnable: DDL ignores ORA-01430 / ORA-00955; LIBQUERY DELETE+INSERT.
--
-- Columns (issue / resolution / notes as HTML CLOB — same pattern as ALERTS.ALTSPEC):
--   BUGID, BALTID, BUGPATCHDAY, BUGRELEASEDATE,
--   BUGISSUE, BUGRESOLUTION, BUGNOTES,
--   BUGDCRE, BUGDMAJ, BUGUTIL
--
-- LIBQUERY:
--   ALT0000040  GET  list by alert id
--   ALT0000041  GET  one by bug id
--   ALT0000042  POST MERGE (insert/update)
--   ALT0000043  POST DELETE by bug id
-- =============================================================================

SET DEFINE OFF;
SET SQLBLANKLINES ON;

-- ── DDL (run once; safe to re-run) ───────────────────────────────────────────
-- Avoid q'[...]' / NULLS LAST in CREATE INDEX (ORA-00907 on older Oracle).
DECLARE
  v_cnt NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_cnt
    FROM user_tables
   WHERE table_name = 'ALERTBUG';

  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE TABLE ALERTBUG (' ||
      '  BUGID            VARCHAR2(50) NOT NULL,' ||
      '  BALTID           VARCHAR2(50) NOT NULL,' ||
      '  BUGPATCHDAY      DATE,' ||
      '  BUGRELEASEDATE   DATE,' ||
      '  BUGISSUE         CLOB,' ||
      '  BUGRESOLUTION    CLOB,' ||
      '  BUGNOTES         CLOB,' ||
      '  BUGDCRE          DATE DEFAULT SYSDATE,' ||
      '  BUGDMAJ          DATE,' ||
      '  BUGUTIL          VARCHAR2(50),' ||
      '  CONSTRAINT PK_ALERTBUG PRIMARY KEY (BUGID)' ||
      ')';
    DBMS_OUTPUT.PUT_LINE('ALERTBUG created.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('ALERTBUG already exists - skipped.');
  END IF;
END;
/

