-- SET0000035 — List dashboard widgets for a user
INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000035',
       'User widget - list',
       'USER_WIDGET rows for user. :param1=UWPUSERID.',
       q'~
SELECT uw.UWPUSERID,
       uw.UWPWIDID,
       uw.UWPPARAM,
       uw.UWPDESC,
       uw.UWPCONTAINER,
       uw.UWPW_X,
       uw.UWPW_Y,
       uw.UWPWIDTH,
       uw.UWPHEIGHT,
       uw.UWPROWS,
       uw.UWPCOLLAPSE,
       uw.UWPENABLE,
       uw.UWPDCRE,
       uw.UWPDMAJ,
       uw.UWPUTIL,
       tn.TWLADESC AS WIDNAME_DESC
  FROM USER_WIDGET uw
  LEFT JOIN WIDGET w ON w.WIDID = uw.UWPWIDID
  LEFT JOIN TRA_WIDGETS tn ON tn.TWLAID = w.WIDNAME AND tn.TWLALANGUE = 'us_US'
 WHERE uw.UWPUSERID = :param1
 ORDER BY uw.UWPW_Y, uw.UWPW_X, uw.UWPWIDID, uw.UWPPARAM
~',
       ':param1=userid',
       'UWPUSERID,UWPWIDID,UWPPARAM,UWPDESC,UWPCONTAINER,UWPW_X,UWPW_Y,UWPWIDTH,UWPHEIGHT,UWPROWS,UWPCOLLAPSE,UWPENABLE,UWPDCRE,UWPDMAJ,UWPUTIL,WIDNAME_DESC',
       0, 0, 0 FROM dual;

