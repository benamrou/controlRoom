INSERT INTO LIBQUERY (
  QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT,
  QUERYACCESS, QUERYTYPE, QUERYUPDATE
)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000072',
       'News - MERGE',
       'Body values NEWS_ID,ITEM_TYPE,TITLE,BODY,PUBLISHED,ICON,NOTIFICATION_DATE,NOTIFICATION_MSG,UPDATED_BY. NEWS_ID 0 = insert. Admin only. ICON=emoji.',
       q'~
MERGE INTO ICR_NEWS tgt
USING (
  SELECT CASE
           WHEN NVL(TO_NUMBER(jt.NEWS_ID), 0) > 0 THEN TO_NUMBER(jt.NEWS_ID)
           ELSE (SELECT NVL(MAX(NEWS_ID), 0) + 1 FROM ICR_NEWS)
         END NEWS_ID,
         UPPER(TRIM(jt.ITEM_TYPE)) ITEM_TYPE,
         jt.TITLE TITLE,
         jt.BODY,
         NVL(TO_NUMBER(jt.PUBLISHED), 1) PUBLISHED,
         CASE
           WHEN jt.NOTIFICATION_DATE IS NULL OR TRIM(jt.NOTIFICATION_DATE) IS NULL THEN CAST(NULL AS DATE)
           ELSE TO_DATE(SUBSTR(TRIM(jt.NOTIFICATION_DATE), 1, 10), 'YYYY-MM-DD')
         END NOTIFICATION_DATE,
         jt.NOTIFICATION_MSG NOTIFICATION_MSG,
         jt.ICON ICON,
         TRIM(jt.UPDATED_BY) UPDATED_BY
    FROM REQUEST_QUERY_BODY rb,
         JSON_TABLE(rb.REQUESTBODY, '$.values[0]'
           COLUMNS (
             NEWS_ID            VARCHAR2(20)      PATH '$."NEWS_ID"',
             ITEM_TYPE          VARCHAR2(10)      PATH '$."ITEM_TYPE"',
             TITLE              VARCHAR2(400 CHAR) PATH '$."TITLE"',
             BODY               CLOB              PATH '$."BODY"',
             PUBLISHED          VARCHAR2(5)       PATH '$."PUBLISHED"',
             NOTIFICATION_DATE  VARCHAR2(30)      PATH '$."NOTIFICATION_DATE"',
             NOTIFICATION_MSG   CLOB              PATH '$."NOTIFICATION_MSG"',
             ICON               VARCHAR2(100 CHAR) PATH '$."ICON"',
             UPDATED_BY         VARCHAR2(50)      PATH '$."UPDATED_BY"'
           )
         ) jt
   WHERE rb.REQUESTID = :param1
) src
ON (tgt.NEWS_ID = src.NEWS_ID)
WHEN MATCHED THEN UPDATE SET
  tgt.ITEM_TYPE = src.ITEM_TYPE,
  tgt.TITLE = src.TITLE,
  tgt.BODY = src.BODY,
  tgt.PUBLISHED = src.PUBLISHED,
  tgt.NOTIFICATION_DATE = src.NOTIFICATION_DATE,
  tgt.NOTIFICATION_MSG = src.NOTIFICATION_MSG,
  tgt.ICON = src.ICON,
  tgt.PUBLISHED_ON = CASE WHEN src.PUBLISHED = 1 THEN NVL(tgt.PUBLISHED_ON, SYSDATE) ELSE tgt.PUBLISHED_ON END,
  tgt.PUBLISHED_BY = CASE WHEN src.PUBLISHED = 1 THEN NVL(tgt.PUBLISHED_BY, src.UPDATED_BY) ELSE tgt.PUBLISHED_BY END,
  tgt.UPDATED_ON = SYSDATE,
  tgt.UPDATED_BY = src.UPDATED_BY
WHEN NOT MATCHED THEN INSERT (
  NEWS_ID, ITEM_TYPE, TITLE, BODY, PUBLISHED, PUBLISHED_ON, PUBLISHED_BY,
  NOTIFICATION_DATE, NOTIFICATION_MSG, ICON,
  CREATED_ON, UPDATED_ON, CREATED_BY, UPDATED_BY)
VALUES (
  src.NEWS_ID,
  src.ITEM_TYPE, src.TITLE, src.BODY, src.PUBLISHED,
  CASE WHEN src.PUBLISHED = 1 THEN SYSDATE ELSE NULL END,
  CASE WHEN src.PUBLISHED = 1 THEN src.UPDATED_BY ELSE NULL END,
  src.NOTIFICATION_DATE, src.NOTIFICATION_MSG, src.ICON,
  SYSDATE, SYSDATE, src.UPDATED_BY, src.UPDATED_BY)
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

