-- =============================================================================
-- 120_icr_news_patch.sql
-- Header What's new: ICR_NEWS + LIBQUERY SET0000070-0074
-- Incremental -- safe to re-run. DDL is idempotent (CREATE if missing + ALTER extra columns).
-- NOTIFICATION_DATE: login banner is shown through that calendar day (NULL = no auto banner).
-- NOTIFICATION_MSG: short text shown in the login banner (BODY stays on the archive).
-- Mail list (SET0000070) returns every published item; SET0000074 is the login banner slice.
--
-- SET0000070 GET published (everyone -- full archive)
-- SET0000071 GET all (admin)
-- SET0000072 MERGE (admin)
-- SET0000073 DELETE (admin)
-- SET0000074 GET login banner (published + NOTIFICATION_DATE still active)
-- HDR_NEWS_MAIL -- toolbar newspaper (MENU_TYPE HEADER, excluded from profile dropdown)
-- =============================================================================

SET DEFINE OFF;
SET SCAN OFF;

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'ICR_NEWS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE
      'CREATE TABLE ICR_NEWS (
         NEWS_ID            NUMBER         NOT NULL,
         ITEM_TYPE          VARCHAR2(10)   NOT NULL,
         TITLE              NVARCHAR2(200) NOT NULL,
         BODY               CLOB,
         PUBLISHED          NUMBER(1)      DEFAULT 1 NOT NULL,
         PUBLISHED_ON       DATE,
         PUBLISHED_BY       VARCHAR2(50),
         NOTIFICATION_DATE  DATE,
         NOTIFICATION_MSG   NVARCHAR2(2000),
         ICON               NVARCHAR2(40),
         CREATED_ON         DATE           DEFAULT SYSDATE,
         UPDATED_ON         DATE,
         CREATED_BY         VARCHAR2(50),
         UPDATED_BY         VARCHAR2(50),
         CONSTRAINT pk_icr_news PRIMARY KEY (NEWS_ID),
         CONSTRAINT chk_icr_news_type CHECK (ITEM_TYPE IN (''NEWS'',''PATCH'')),
         CONSTRAINT chk_icr_news_pub CHECK (PUBLISHED IN (0,1))
       )';
  END IF;
END;
/

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tab_columns
   WHERE table_name = 'ICR_NEWS' AND column_name = 'NOTIFICATION_DATE';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS ADD NOTIFICATION_DATE DATE';
  END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns
   WHERE table_name = 'ICR_NEWS' AND column_name = 'NOTIFICATION_MSG';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS ADD NOTIFICATION_MSG NVARCHAR2(2000)';
  END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns
   WHERE table_name = 'ICR_NEWS' AND column_name = 'ICON';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS ADD ICON NVARCHAR2(40)';
  END IF;
END;
/

BEGIN
  FOR r IN (
    SELECT column_name, data_type, char_length
      FROM user_tab_columns
     WHERE table_name = 'ICR_NEWS'
       AND column_name IN ('TITLE','NOTIFICATION_MSG','BODY')
  ) LOOP
    IF r.column_name = 'TITLE' AND r.data_type = 'VARCHAR2' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS MODIFY TITLE NVARCHAR2(200)';
    ELSIF r.column_name = 'NOTIFICATION_MSG' AND r.data_type = 'VARCHAR2' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS MODIFY NOTIFICATION_MSG NVARCHAR2(2000)';
    ELSIF r.column_name = 'BODY' AND r.data_type = 'VARCHAR2' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ICR_NEWS MODIFY BODY CLOB';
    END IF;
  END LOOP;
END;
