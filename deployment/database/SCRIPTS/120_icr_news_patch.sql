       '',
       0, 0, 1 FROM dual;

INSERT INTO LIBQUERY (
  QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT,
  QUERYACCESS, QUERYTYPE, QUERYUPDATE
)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000074',
       'News - login banner',
       'Published items with an active NOTIFICATION_DATE and NOTIFICATION_MSG (login popup). :param1 unused (-1).',
       q'~SELECT NEWS_ID, ITEM_TYPE, TITLE, NOTIFICATION_MSG, ICON, PUBLISHED,
       TO_CHAR(NVL(PUBLISHED_ON, CREATED_ON), 'MM/DD/YYYY HH24:MI') PUBLISHED_ON,
       NVL(PUBLISHED_BY, CREATED_BY) PUBLISHED_BY,
       TO_CHAR(NOTIFICATION_DATE, 'YYYY-MM-DD') NOTIFICATION_DATE
  FROM ICR_NEWS
 WHERE PUBLISHED = 1
   AND NOTIFICATION_DATE IS NOT NULL
   AND TRIM(NOTIFICATION_MSG) IS NOT NULL
   AND TRUNC(NOTIFICATION_DATE) >= TRUNC(SYSDATE)
   AND :param1 = :param1
 ORDER BY NVL(PUBLISHED_ON, CREATED_ON) DESC, NEWS_ID DESC~',
       ':param1=unused',
       'NEWS_ID,ITEM_TYPE,TITLE,NOTIFICATION_MSG,ICON,PUBLISHED,PUBLISHED_ON,PUBLISHED_BY,NOTIFICATION_DATE',
       1, 0, 0 FROM dual;

