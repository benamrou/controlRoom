  src.USERFNAME,src.USERLNAME,src.USEREMAIL,src.USERMOBILE,src.USERTEAM,src.USERACTIVE,src.USERMOBEMAIL,
  src.USERDATAINTEGRITY,src.USERIT,src.USERBUYER,src.USERHELPDESK,src.USERWAREHOUSE,
  src.USERSPACEPLANNING,src.USERSTECH,src.USERAIADMIN,src.USERAIDESIGNER,src.USERTYPE,
  SYSDATE,SYSDATE,src.USERUTIL)
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

