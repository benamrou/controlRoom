DELETE FROM LIBQUERY WHERE QUERYNUM IN ('SET0000020', 'SET0000021', 'SET0000022');

INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000020',
       'Users - list',
       'List users. :param1=USERCORPID or -1; :param2=USERACTIVE or -1.',
       q'~SELECT u.USERID, u.USERCORPID, c.CORPCODE, u.USERFNAME, u.USERLNAME, u.USEREMAIL,
       u.USERACTIVE, u.USERAPPLI, u.USERPROF, u.USERLANG, NVL(u.USERTYPE, 0) USERTYPE,
       u.USERDMAJ, u.USERUTIL
  FROM USERSROOM u
  LEFT JOIN CORPORATE c ON c.CORPID = u.USERCORPID
 WHERE (:param1 = '-1' OR u.USERCORPID = TO_NUMBER(:param1))
   AND (:param2 = '-1' OR u.USERACTIVE = TO_NUMBER(:param2))
 ORDER BY u.USERID~',
       ':param1=corpid,:param2=active',
       'USERID,USERCORPID,CORPCODE,USERFNAME,USERLNAME,USEREMAIL,USERACTIVE,USERAPPLI,USERPROF,USERLANG,USERTYPE,USERDMAJ,USERUTIL',
       0, 0, 0 FROM dual;

