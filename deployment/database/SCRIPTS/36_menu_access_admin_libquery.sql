-- SET0000047 — MERGE menu entry
INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000047',
       'Menu admin - entry MERGE',
       'Body {values:[{MENU_CODE,PARENT_CODE,MENU_TYPE,MENU_MODE,ROUTE_PATH,ICON_CLASS,LABEL_TEXT,SORT_ORDER,EXPAND_KEY,ACTIVE}]}.',
       q'~
MERGE INTO ICR_MENU_ENTRY tgt
USING (
  SELECT jt.MENU_CODE,
         NULLIF(TRIM(jt.PARENT_CODE), '') PARENT_CODE,
         jt.MENU_TYPE, jt.MENU_MODE,
         NULLIF(TRIM(jt.ROUTE_PATH), '') ROUTE_PATH,
         NULLIF(TRIM(jt.ICON_CLASS), '') ICON_CLASS,
         jt.LABEL_TEXT,
         NVL(TO_NUMBER(jt.SORT_ORDER), 0) SORT_ORDER,
         NULLIF(TRIM(jt.EXPAND_KEY), '') EXPAND_KEY,
         NVL(TO_NUMBER(jt.ACTIVE), 1) ACTIVE
    FROM REQUEST_QUERY_BODY rb,
         JSON_TABLE(rb.REQUESTBODY, '$.values[0]'
           COLUMNS (
             MENU_CODE   VARCHAR2(60)  PATH '$."MENU_CODE"',
             PARENT_CODE VARCHAR2(60)  PATH '$."PARENT_CODE"',
             MENU_TYPE   VARCHAR2(20)  PATH '$."MENU_TYPE"',
             MENU_MODE   VARCHAR2(10)  PATH '$."MENU_MODE"',
             ROUTE_PATH  VARCHAR2(200) PATH '$."ROUTE_PATH"',
             ICON_CLASS  VARCHAR2(80)  PATH '$."ICON_CLASS"',
             LABEL_TEXT  VARCHAR2(120) PATH '$."LABEL_TEXT"',
             SORT_ORDER  VARCHAR2(10)  PATH '$."SORT_ORDER"',
             EXPAND_KEY  VARCHAR2(40)  PATH '$."EXPAND_KEY"',
             ACTIVE      VARCHAR2(5)   PATH '$."ACTIVE"'
           )
         ) jt
   WHERE rb.REQUESTID = :param1
) src
ON (tgt.MENU_CODE = src.MENU_CODE)
WHEN MATCHED THEN UPDATE SET
  tgt.PARENT_CODE = src.PARENT_CODE, tgt.MENU_TYPE = src.MENU_TYPE, tgt.MENU_MODE = src.MENU_MODE,
  tgt.ROUTE_PATH = src.ROUTE_PATH, tgt.ICON_CLASS = src.ICON_CLASS, tgt.LABEL_TEXT = src.LABEL_TEXT,
  tgt.SORT_ORDER = src.SORT_ORDER, tgt.EXPAND_KEY = src.EXPAND_KEY, tgt.ACTIVE = src.ACTIVE
WHEN NOT MATCHED THEN INSERT (
  MENU_CODE, PARENT_CODE, MENU_TYPE, MENU_MODE, ROUTE_PATH, ICON_CLASS, LABEL_TEXT, SORT_ORDER, EXPAND_KEY, ACTIVE)
VALUES (src.MENU_CODE, src.PARENT_CODE, src.MENU_TYPE, src.MENU_MODE, src.ROUTE_PATH, src.ICON_CLASS,
        src.LABEL_TEXT, src.SORT_ORDER, src.EXPAND_KEY, src.ACTIVE)
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

