-- SET0000054 — Replace all grants for a profile (bulk save)
INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'SET0000054',
       'Menu admin - profile menus replace',
       'Body {values:[{PROFILE_ID,MENU_CODES}]}. MENU_CODES = comma-separated MENU_CODE list (granted).',
       q'~
DECLARE
  v_prof NUMBER;
  v_codes VARCHAR2(4000);
BEGIN
  SELECT TO_NUMBER(jt.PROFILE_ID), jt.MENU_CODES
    INTO v_prof, v_codes
    FROM REQUEST_QUERY_BODY rb,
         JSON_TABLE(rb.REQUESTBODY, '$.values[0]'
           COLUMNS (
             PROFILE_ID VARCHAR2(20)  PATH '$."PROFILE_ID"',
             MENU_CODES VARCHAR2(4000) PATH '$."MENU_CODES"'
           )
         ) jt
   WHERE rb.REQUESTID = :param1;

  DELETE FROM ICR_PROFILE_MENU WHERE PROFILE_ID = v_prof;

  IF v_codes IS NOT NULL AND TRIM(v_codes) IS NOT NULL THEN
    INSERT INTO ICR_PROFILE_MENU (PROFILE_ID, MENU_CODE, GRANTED)
    SELECT v_prof, TRIM(REGEXP_SUBSTR(v_codes, '[^,]+', 1, LEVEL)), 1
      FROM dual
     CONNECT BY REGEXP_SUBSTR(v_codes, '[^,]+', 1, LEVEL) IS NOT NULL;
  END IF;
END;
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

