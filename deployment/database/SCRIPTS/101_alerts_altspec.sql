            s.ALTFORMATTAB2XLS, s.ALTNOHTML, s.ALTSQL, s.ALTSPEC)
~',
       '{:USERID, :DATABASE_SID,:LISTE_PARAM,:LANGUAGE}',
       '',
       1,
       0,
       1
  FROM dual;

COMMIT;

SET DEFINE ON;

