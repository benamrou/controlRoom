-- WDG0000105 — MERGE widget result column
INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'WDG0000105',
       'Widget library — save result column',
       'POST :param1=REQUESTID. values[]: WRSID, WRSFIELD, WRSHEADER, WRSPOSITION, ACTOR.',
       q'~
MERGE INTO WIDGETRESULT t
USING (
  SELECT TRIM(j.WRSID) AS WRSID,
         TRIM(j.WRSFIELD) AS WRSFIELD,
         TRIM(j.WRSHEADER) AS WRSHEADER,
         CASE WHEN NULLIF(TRIM(j.WRSPOSITION), '') IS NOT NULL THEN TO_NUMBER(TRIM(j.WRSPOSITION)) END AS WRSPOSITION,
         TRIM(j.ACTOR) AS ACTOR
    FROM json_table(
           (SELECT r.requestbody FROM request_query_body r WHERE r.requestid = TO_NUMBER(TRIM(:param1))),
           '$.values[*]'
           COLUMNS (
             WRSID       VARCHAR2(20)  PATH '$."WRSID"',
             WRSFIELD    VARCHAR2(100) PATH '$."WRSFIELD"',
             WRSHEADER   VARCHAR2(100) PATH '$."WRSHEADER"',
             WRSPOSITION VARCHAR2(20)  PATH '$."WRSPOSITION"',
             ACTOR       VARCHAR2(50)  PATH '$."ACTOR"'
           )
         ) j
) s
ON (t.WRSID = s.WRSID AND t.WRSFIELD = s.WRSFIELD)
WHEN MATCHED THEN UPDATE SET
  t.WRSHEADER = s.WRSHEADER,
  t.WRSPOSITION = s.WRSPOSITION,
  t.WRSDMAJ = SYSDATE,
  t.WRSUTIL = s.ACTOR
WHEN NOT MATCHED THEN INSERT (
  WRSID, WRSFIELD, WRSHEADER, WRSPOSITION, WRSDCRE, WRSDMAJ, WRSUTIL
) VALUES (
  s.WRSID, s.WRSFIELD, s.WRSHEADER, s.WRSPOSITION, SYSDATE, SYSDATE, s.ACTOR
)
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

