-- WDG0000103 — DELETE widget (cascades related rows)
INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'WDG0000103',
       'Widget library - delete widget',
       'POST :param1=REQUESTID. values[]: WIDID. Cascades child rows then WIDGET.',
       q'~
BEGIN
  FOR rec IN (
    SELECT TRIM(j.WIDID) AS wid
      FROM json_table(
             (SELECT r.requestbody
                FROM request_query_body r
               WHERE r.requestid = TO_NUMBER(TRIM(:param1))),
             '$.values[*]'
             COLUMNS (WIDID VARCHAR2(20) PATH '$."WIDID"')
           ) j
     WHERE TRIM(j.WIDID) IS NOT NULL
  ) LOOP
    DELETE FROM WIDGETRESULT WHERE WRSID = rec.wid;
    DELETE FROM WIDGETLINK WHERE LWQMWIDID = rec.wid OR LWQCWIDID = rec.wid;
    DELETE FROM USER_WIDGET WHERE UWPWIDID = rec.wid;
    DELETE FROM WIDGETUSERPREF WHERE WPFWIDID = rec.wid;
    DELETE FROM TRA_WIDGETS WHERE TWLAID IN (
      SELECT w.WIDNAME FROM WIDGET w WHERE w.WIDID = rec.wid
      UNION
      SELECT w.WIDDESC FROM WIDGET w WHERE w.WIDID = rec.wid
    );
    DELETE FROM WIDGET WHERE WIDID = rec.wid;
  END LOOP;
END;
~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

