-- Copy widget TRA_WIDGETS us_US text to en_GB and fr_FR (same text until translated)
MERGE INTO TRA_WIDGETS t
USING (
  SELECT w.TWLAID, 'en_GB' AS TWLALANGUE, w.TWLADESC, w.TWLAUTIL
    FROM TRA_WIDGETS w
   WHERE w.TWLALANGUE = 'us_US'
) s
ON (t.TWLAID = s.TWLAID AND t.TWLALANGUE = s.TWLALANGUE)
WHEN MATCHED THEN UPDATE SET t.TWLADESC = s.TWLADESC, t.TWLADMAJ = SYSDATE
WHEN NOT MATCHED THEN INSERT (TWLAID, TWLADESC, TWLALANGUE, TWLADCRE, TWLADMAJ, TWLAUTIL)
VALUES (s.TWLAID, s.TWLADESC, s.TWLALANGUE, SYSDATE, SYSDATE, s.TWLAUTIL);

MERGE INTO TRA_WIDGETS t
USING (
  SELECT w.TWLAID, 'fr_FR' AS TWLALANGUE, w.TWLADESC, w.TWLAUTIL
    FROM TRA_WIDGETS w
   WHERE w.TWLALANGUE = 'us_US'
) s
ON (t.TWLAID = s.TWLAID AND t.TWLALANGUE = s.TWLALANGUE)
WHEN MATCHED THEN UPDATE SET t.TWLADESC = s.TWLADESC, t.TWLADMAJ = SYSDATE
WHEN NOT MATCHED THEN INSERT (TWLAID, TWLADESC, TWLALANGUE, TWLADCRE, TWLADMAJ, TWLAUTIL)
VALUES (s.TWLAID, s.TWLADESC, s.TWLALANGUE, SYSDATE, SYSDATE, s.TWLAUTIL);

-- WDG0000110 — accept TWLALANGUE in POST body
DELETE FROM LIBQUERY WHERE QUERYNUM IN ('WDG0000110', 'WDG0000100');

INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'WDG0000110',
       'Widget library - save TRA_WIDGETS row',
       'POST :param1=REQUESTID. values[]: TWLAID, TWLADESC, TWLALANGUE, ACTOR.',
       q'~MERGE INTO TRA_WIDGETS tt USING (SELECT TRIM(j.TWLAID) TWLAID,NVL(NULLIF(TRIM(j.TWLALANGUE),''),'us_US') TWLALANGUE,SUBSTR(NVL(NULLIF(TRIM(j.TWLADESC),''),' '),1,100) TWLADESC,TRIM(j.ACTOR) TWLAUTIL FROM json_table((SELECT r.requestbody FROM request_query_body r WHERE r.requestid=TO_NUMBER(:param1)),'$.values[*]' COLUMNS (TWLAID VARCHAR2(20) PATH '$."TWLAID"',TWLADESC VARCHAR2(100) PATH '$."TWLADESC"',TWLALANGUE VARCHAR2(10) PATH '$."TWLALANGUE"',ACTOR VARCHAR2(50) PATH '$."ACTOR"')) j WHERE TRIM(j.TWLAID) IS NOT NULL) src ON (tt.TWLAID=src.TWLAID AND tt.TWLALANGUE=src.TWLALANGUE) WHEN MATCHED THEN UPDATE SET tt.TWLADESC=src.TWLADESC,tt.TWLADMAJ=SYSDATE,tt.TWLAUTIL=src.TWLAUTIL WHEN NOT MATCHED THEN INSERT (TWLAID,TWLADESC,TWLALANGUE,TWLADCRE,TWLADMAJ,TWLAUTIL) VALUES (src.TWLAID,src.TWLADESC,src.TWLALANGUE,SYSDATE,SYSDATE,src.TWLAUTIL)~',
       ':param1=REQUESTID',
       '',
       0, 0, 1 FROM dual;

INSERT INTO LIBQUERY (QUERYID, QUERYNUM, QUERYTITLE, QUERYDESC, QUERYSQL, QUERYPARAM, QUERYRESULT, QUERYACCESS, QUERYTYPE, QUERYUPDATE)
SELECT (SELECT NVL(MAX(QUERYID), 0) + 1 FROM LIBQUERY),
       'WDG0000100',
       'Widget library — list',
       'List widgets. :param1=active (-1=all). :param2=TWLALANGUE.',
       q'~
SELECT w.WIDID,
       w.WIDNAME,
       w.WIDDESC,
       NVL(tn.TWLADESC, tn_us.TWLADESC) AS WIDNAME_DESC,
       NVL(td.TWLADESC, td_us.TWLADESC) AS WIDDESC_DESC,
       w.WIDBEHAVIOR,
       w.WIDTABLE,
       w.WIDRSS,
       w.WIDCHART,
       w.WIDINFO,
       w.WIDWIDTH,
       w.WIDHEIGHT,
       w.WIDROWS,
       w.WIDSNAP,
       w.WIDSNAPFILE,
       w.WIDCHARTX,
       w.WIDCHARTDATA,
       w.WIDCHARTLEGEND,
       w.WIDCHARTLEGENDINFO,
       w.WIDCHARTNBSET,
       w.WIDCHARTTYPE,
       w.WIDCHARTUNIT,
       w.WIDCARD,
       w.WIDMAINID,
       w.WIDDCRE,
       w.WIDDMAJ,
       w.WIDUTIL
  FROM WIDGET w
  LEFT JOIN TRA_WIDGETS tn
    ON tn.TWLAID = w.WIDNAME AND tn.TWLALANGUE = :param2
  LEFT JOIN TRA_WIDGETS tn_us
    ON tn_us.TWLAID = w.WIDNAME AND tn_us.TWLALANGUE = 'us_US'
  LEFT JOIN TRA_WIDGETS td
    ON td.TWLAID = w.WIDDESC AND td.TWLALANGUE = :param2
  LEFT JOIN TRA_WIDGETS td_us
    ON td_us.TWLAID = w.WIDDESC AND td_us.TWLALANGUE = 'us_US'
 ORDER BY UPPER(NVL(tn.TWLADESC, NVL(tn_us.TWLADESC, w.WIDNAME))), w.WIDID
~',
       ':param1=active_filter,:param2=language',
       'WIDID,WIDNAME,WIDDESC,WIDNAME_DESC,WIDDESC_DESC,WIDBEHAVIOR,WIDTABLE,WIDRSS,WIDCHART,WIDINFO,WIDWIDTH,WIDHEIGHT,WIDROWS,WIDSNAP,WIDSNAPFILE,WIDCHARTX,WIDCHARTDATA,WIDCHARTLEGEND,WIDCHARTLEGENDINFO,WIDCHARTNBSET,WIDCHARTTYPE,WIDCHARTUNIT,WIDCARD,WIDMAINID,WIDDCRE,WIDDMAJ,WIDUTIL',
       0, 0, 0 FROM dual;

