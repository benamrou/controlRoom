DECLARE
  PROCEDURE upsert_label(p_id VARCHAR2, p_lang VARCHAR2, p_desc VARCHAR2, p_screen VARCHAR2) IS
  BEGIN
    MERGE INTO TRA_LABELS t
    USING (SELECT p_id TLAID, p_lang TLALANGUE FROM DUAL) s
    ON (t.TLAID = s.TLAID AND t.TLALANGUE = s.TLALANGUE)
    WHEN MATCHED THEN UPDATE SET t.TLADESC = p_desc, t.TLASCREEN = p_screen, t.TLADMAJ = SYSDATE
    WHEN NOT MATCHED THEN INSERT (TLAID, TLADESC, TLAMENU, TLASCREEN, TLALANGUE, TLADCRE, TLADMAJ, TLAUTIL)
    VALUES (p_id, p_desc, 0, p_screen, p_lang, SYSDATE, SYSDATE, 'admin');
  END;
BEGIN
  upsert_label('S01.TITLE', 'us_US', 'Recent Activities Overview', 'SCR0000000001');
  upsert_label('S01.TITLE', 'en_GB', 'Recent Activities Overview', 'SCR0000000001');
  upsert_label('S01.TITLE', 'fr_FR', 'Apercu des activites recentes', 'SCR0000000001');
  upsert_label('S01.BTN.ADD', 'us_US', 'Add a widget', 'SCR0000000001');
  upsert_label('S01.BTN.ADD', 'en_GB', 'Add a widget', 'SCR0000000001');
  upsert_label('S01.BTN.ADD', 'fr_FR', 'Ajouter un widget', 'SCR0000000001');
  upsert_label('S01.BTN.SAVE', 'us_US', 'Save layout', 'SCR0000000001');
  upsert_label('S01.BTN.SAVE', 'en_GB', 'Save layout', 'SCR0000000001');
  upsert_label('S01.BTN.SAVE', 'fr_FR', 'Enregistrer la disposition', 'SCR0000000001');
END;
/

