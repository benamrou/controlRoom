  SELECT TO_NUMBER(jt.PROFILE_ID) PROFILE_ID, jt.MENU_CODE, NVL(TO_NUMBER(jt.GRANTED), 1) GRANTED
    FROM REQUEST_QUERY_BODY rb,
         JSON_TABLE(rb.REQUESTBODY, '$.values[0]'
