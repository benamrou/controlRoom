             MENU_CODE  VARCHAR2(60) PATH '$."MENU_CODE"',
             GRANTED    VARCHAR2(5)  PATH '$."GRANTED"'
           )
         ) jt
   WHERE rb.REQUESTID = :param1
) src
ON (tgt.PROFILE_ID = src.PROFILE_ID AND tgt.MENU_CODE = src.MENU_CODE)
WHEN MATCHED THEN UPDATE SET tgt.GRANTED = src.GRANTED
WHEN NOT MATCHED THEN INSERT (PROFILE_ID, MENU_CODE, GRANTED)
VALUES (src.PROFILE_ID, src.MENU_CODE, src.GRANTED)
